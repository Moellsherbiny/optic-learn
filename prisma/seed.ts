async function main() {
  const teacherEmail = process.env.COURSE_TEACHER_EMAIL;

  const teacher = teacherEmail
    ? await prisma.user.findUnique({ where: { email: teacherEmail } })
    : await prisma.user.findFirst({ where: { role: "TEACHER" } });

  if (!teacher) {
    throw new Error(
      teacherEmail
        ? `No user found with COURSE_TEACHER_EMAIL=${teacherEmail}`
        : "No TEACHER user found. Set COURSE_TEACHER_EMAIL in .env to an existing teacher account.",
    );
  }

  if (teacher.role !== "TEACHER" && teacher.role !== "ADMIN") {
    throw new Error("The selected course owner must have TEACHER or ADMIN role.");
  }

  const existingCourse = await prisma.course.findFirst({
    where: { title: courseTitle, teacherId: teacher.id },
  });

  const course = existingCourse
    ? await prisma.course.update({
        where: { id: existingCourse.id },
        data: {
          description: courseDescription,
        },
      })
    : await prisma.course.create({
        data: {
          title: courseTitle,
          description: courseDescription,
          teacherId: teacher.id,
        },
      });

  let createdModules = 0;
  let updatedModules = 0;
  let createdLessons = 0;
  let updatedLessons = 0;

  for (const moduleData of modules) {
    const existingModule = await prisma.module.findFirst({
      where: { courseId: course.id, order: moduleData.order },
    });

    const module = existingModule
      ? await prisma.module.update({
          where: { id: existingModule.id },
          data: {
            title: moduleData.title,
            description: moduleData.description,
            level: StudentLevel.BEGINNER,
          },
        })
      : await prisma.module.create({
          data: {
            title: moduleData.title,
            description: moduleData.description,
            courseId: course.id,
            order: moduleData.order,
            level: StudentLevel.BEGINNER,
          },
        });

    if (existingModule) updatedModules++;
    else createdModules++;

    for (const lessonData of moduleData.lessons) {
      const existingLesson = await prisma.lesson.findFirst({
        where: { moduleId: module.id, order: lessonData.order },
      });

      const lessonFields = {
        title: lessonData.title,
        content: lessonData.content,
        type: LessonType.TEXT,
      };

      if (existingLesson) {
        await prisma.lesson.update({
          where: { id: existingLesson.id },
          data: lessonFields,
        });
        updatedLessons++;
      } else {
        await prisma.lesson.create({
          data: {
            ...lessonFields,
            moduleId: module.id,
            order: lessonData.order,
          },
        });
        createdLessons++;
      }
    }
  }

  console.log("Course seed completed successfully.");
  console.log({
    courseId: course.id,
    courseTitle: course.title,
    teacherEmail: teacher.email,
    modulesCreated: createdModules,
    modulesUpdated: updatedModules,
    lessonsCreated: createdLessons,
    lessonsUpdated: updatedLessons,
    totalModules: modules.length,
    totalLessons: modules.reduce((sum, item) => sum + item.lessons.length, 0),
  });
}

